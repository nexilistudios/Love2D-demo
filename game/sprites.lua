-- Procedural pixel-art sprites. Every sprite is defined as an array of strings
-- (one character per pixel) and baked into LÖVE images at load time. The
-- player sprites use the palette keys "1" (primary) and "2" (secondary) so a
-- single set of maps can be recoloured for different player characters.

local Config = require("config")

local Sprites = {}

local cache = {}

local function make_image(rows, palette)
    local height = #rows
    local width = 0
    for _, row in ipairs(rows) do
        width = math.max(width, #row)
    end
    assert(width > 0 and height > 0, "empty sprite map")

    local data = love.image.newImageData(width, height)
    for y = 1, height do
        local row = rows[y]
        for x = 1, width do
            local key = row:sub(x, x)
            local color = palette[key]
            if color and key ~= "." then
                data:setPixel(x - 1, y - 1, color[1], color[2], color[3], 1)
            end
        end
    end
    local image = love.graphics.newImage(data)
    image:setFilter("nearest", "nearest")
    return image
end

local function keyed(tbl, key)
    if cache[key] then return cache[key] end
    local image = make_image(tbl.rows, tbl.palette or Config.PALETTE)
    cache[key] = image
    return image
end

-- Merge a base palette with character colours.
local function character_palette(index)
    local c = Config.CHARACTERS[index] or Config.CHARACTERS[1]
    local p = {}
    for k, v in pairs(Config.PALETTE) do p[k] = v end
    p["1"] = c.primary
    p["2"] = c.secondary
    return p
end

-- Fire power paints the overalls white and keeps the character's colour.
local function fire_palette(index)
    local p = character_palette(index)
    p["1"] = { 0.98, 0.98, 0.98 }
    p["2"] = (Config.CHARACTERS[index] or Config.CHARACTERS[1]).primary
    return p
end

