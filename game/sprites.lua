local player_images = {}

function Sprites.build()
    if Sprites.ready then return end

    -- Player images for every character, normal and fire powered.
    for index = 1, #Config.CHARACTERS do
        local palette = character_palette(index)
        local fire = fire_palette(index)
        local set = { small = {}, big = {} }
        set.fire = { small = {}, big = {} }
        for name, rows in pairs(SMALL) do
            set.small[name] = make_image(rows, palette)
            set.fire.small[name] = make_image(rows, fire)
        end
        for name, rows in pairs(BIG) do
            set.big[name] = make_image(rows, palette)
            set.fire.big[name] = make_image(rows, fire)
        end
        player_images[index] = set
    end

    -- Named sprites from the fixed palette.
    for name, rows in pairs(ENEMY) do
        cache[name] = make_image(rows, Config.PALETTE)
    end
    for name, rows in pairs(TILE) do
        cache[name] = make_image(rows, Config.PALETTE)
    end

    -- Decoration sprites built from simple shapes.
    Sprites.ready = true
end

function Sprites.player(character, size, frame, fire)
    local set = player_images[character] or player_images[1]
    local group = (fire and set.fire) or set
    local frames = group[size] or group.small
    return frames[frame] or frames.idle
end

function Sprites.get(name)
    return cache[name]
end

return Sprites
